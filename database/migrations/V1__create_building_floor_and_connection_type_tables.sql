CREATE TABLE buildings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(120) NOT NULL,
    description varchar(500),
    building_type varchar(50) NOT NULL,
    address varchar(255),
    CONSTRAINT pk_buildings PRIMARY KEY (id),
    CONSTRAINT uq_buildings_name UNIQUE (name),
    CONSTRAINT ck_buildings_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_buildings_description_not_blank CHECK (description IS NULL OR btrim(description) <> ''),
    CONSTRAINT ck_buildings_type_not_blank CHECK (btrim(building_type) <> ''),
    CONSTRAINT ck_buildings_address_not_blank CHECK (address IS NULL OR btrim(address) <> '')
);

CREATE TABLE floors (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    building_id bigint NOT NULL,
    level integer NOT NULL,
    display_name varchar(40) NOT NULL,
    plan_asset_path varchar(255) NOT NULL,
    plan_width numeric(9,2) NOT NULL,
    plan_height numeric(9,2) NOT NULL,
    metres_per_unit numeric(9,6) NOT NULL,
    CONSTRAINT pk_floors PRIMARY KEY (id),
    CONSTRAINT fk_floors_building_id FOREIGN KEY (building_id) REFERENCES buildings (id),
    CONSTRAINT uq_floors_building_level UNIQUE (building_id, level),
    CONSTRAINT uq_floors_building_display_name UNIQUE (building_id, display_name),
    CONSTRAINT uq_floors_id_building UNIQUE (id, building_id),
    CONSTRAINT ck_floors_display_name_not_blank CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_floors_plan_asset_path CHECK (
        plan_asset_path ~ '^[a-z0-9]([a-z0-9_/-]*[a-z0-9])?\.svg$'
        AND position('..' IN plan_asset_path) = 0
    ),
    CONSTRAINT ck_floors_plan_width_positive CHECK (plan_width > 0),
    CONSTRAINT ck_floors_plan_height_positive CHECK (plan_height > 0),
    CONSTRAINT ck_floors_metres_per_unit_positive CHECK (metres_per_unit > 0)
);

CREATE TABLE connection_types (
    code varchar(30) NOT NULL,
    name varchar(60) NOT NULL,
    speed_mps numeric(5,2) NOT NULL,
    fixed_seconds numeric(6,2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_connection_types PRIMARY KEY (code),
    CONSTRAINT ck_connection_types_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT ck_connection_types_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_connection_types_speed_positive CHECK (speed_mps > 0),
    CONSTRAINT ck_connection_types_fixed_seconds_non_negative CHECK (fixed_seconds >= 0)
);

ALTER TABLE buildings ALTER COLUMN id RESTART WITH 10000;
ALTER TABLE floors ALTER COLUMN id RESTART WITH 10000;
