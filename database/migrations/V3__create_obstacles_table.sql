CREATE TABLE obstacles (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    building_id bigint NOT NULL,
    edge_id bigint,
    node_id bigint,
    obstacle_type varchar(30) NOT NULL,
    description varchar(200) NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT pk_obstacles PRIMARY KEY (id),
    CONSTRAINT fk_obstacles_edge_building FOREIGN KEY (edge_id, building_id)
        REFERENCES edges (id, building_id),
    CONSTRAINT fk_obstacles_node_building FOREIGN KEY (node_id, building_id)
        REFERENCES nodes (id, building_id),
    CONSTRAINT ck_obstacles_exactly_one_target CHECK ((edge_id IS NOT NULL) <> (node_id IS NOT NULL)),
    CONSTRAINT ck_obstacles_type CHECK (obstacle_type IN (
        'BLOCKED_CORRIDOR', 'CLOSED_ROOM', 'BROKEN_ELEVATOR', 'CLOSED_STAIRCASE',
        'CONSTRUCTION_AREA', 'RESTRICTED_CONNECTION'
    )),
    CONSTRAINT ck_obstacles_description_length CHECK (char_length(btrim(description)) BETWEEN 3 AND 200),
    CONSTRAINT ck_obstacles_status CHECK (status IN ('ACTIVE', 'RESOLVED')),
    CONSTRAINT ck_obstacles_version_non_negative CHECK (version >= 0)
);

CREATE INDEX ix_obstacles_building_status ON obstacles (building_id, status);
CREATE UNIQUE INDEX uq_obstacles_active_edge ON obstacles (edge_id)
    WHERE status = 'ACTIVE' AND edge_id IS NOT NULL;
CREATE UNIQUE INDEX uq_obstacles_active_node ON obstacles (node_id)
    WHERE status = 'ACTIVE' AND node_id IS NOT NULL;

ALTER TABLE obstacles ALTER COLUMN id RESTART WITH 10000;
