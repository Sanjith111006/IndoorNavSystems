CREATE TABLE nodes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    building_id bigint NOT NULL,
    floor_id bigint NOT NULL,
    x numeric(9,2) NOT NULL,
    y numeric(9,2) NOT NULL,
    node_type varchar(30) NOT NULL,
    display_name varchar(120),
    accessible boolean NOT NULL DEFAULT true,
    CONSTRAINT pk_nodes PRIMARY KEY (id),
    CONSTRAINT fk_nodes_floor_building FOREIGN KEY (floor_id, building_id)
        REFERENCES floors (id, building_id),
    CONSTRAINT uq_nodes_id_building UNIQUE (id, building_id),
    CONSTRAINT uq_nodes_floor_position UNIQUE (floor_id, x, y),
    CONSTRAINT ck_nodes_x_non_negative CHECK (x >= 0),
    CONSTRAINT ck_nodes_y_non_negative CHECK (y >= 0),
    CONSTRAINT ck_nodes_type CHECK (node_type IN (
        'CORRIDOR_JUNCTION', 'ROOM_ENTRANCE', 'STAIR_LANDING', 'ELEVATOR_ENTRANCE',
        'BUILDING_ENTRANCE', 'FLOOR_TRANSITION', 'POINT_OF_INTEREST'
    )),
    CONSTRAINT ck_nodes_display_name_not_blank CHECK (display_name IS NULL OR btrim(display_name) <> '')
);

CREATE INDEX ix_nodes_floor ON nodes (floor_id);
CREATE INDEX ix_nodes_building ON nodes (building_id);

CREATE TABLE edges (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    building_id bigint NOT NULL,
    from_node_id bigint NOT NULL,
    to_node_id bigint NOT NULL,
    connection_type_code varchar(30) NOT NULL,
    distance_m numeric(8,2) NOT NULL,
    time_seconds numeric(8,2),
    accessible boolean NOT NULL,
    bidirectional boolean NOT NULL DEFAULT true,
    CONSTRAINT pk_edges PRIMARY KEY (id),
    CONSTRAINT fk_edges_from_node_building FOREIGN KEY (from_node_id, building_id)
        REFERENCES nodes (id, building_id),
    CONSTRAINT fk_edges_to_node_building FOREIGN KEY (to_node_id, building_id)
        REFERENCES nodes (id, building_id),
    CONSTRAINT fk_edges_connection_type_code FOREIGN KEY (connection_type_code)
        REFERENCES connection_types (code),
    CONSTRAINT uq_edges_id_building UNIQUE (id, building_id),
    CONSTRAINT ck_edges_distinct_nodes CHECK (from_node_id <> to_node_id),
    CONSTRAINT ck_edges_distance_positive CHECK (distance_m > 0),
    CONSTRAINT ck_edges_time_seconds_positive CHECK (time_seconds IS NULL OR time_seconds > 0)
);

CREATE INDEX ix_edges_from_node ON edges (from_node_id);
CREATE INDEX ix_edges_to_node ON edges (to_node_id);
CREATE INDEX ix_edges_building ON edges (building_id);
CREATE UNIQUE INDEX uq_edges_node_pair_type
    ON edges (LEAST(from_node_id, to_node_id), GREATEST(from_node_id, to_node_id), connection_type_code);

CREATE TABLE rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    floor_id bigint NOT NULL,
    name varchar(120) NOT NULL,
    category varchar(50) NOT NULL,
    description varchar(500),
    bounds_x numeric(9,2) NOT NULL,
    bounds_y numeric(9,2) NOT NULL,
    bounds_width numeric(9,2) NOT NULL,
    bounds_height numeric(9,2) NOT NULL,
    CONSTRAINT pk_rooms PRIMARY KEY (id),
    CONSTRAINT fk_rooms_floor_id FOREIGN KEY (floor_id) REFERENCES floors (id),
    CONSTRAINT uq_rooms_floor_name UNIQUE (floor_id, name),
    CONSTRAINT ck_rooms_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_rooms_category_format CHECK (category ~ '^[a-z][a-z0-9-]*$'),
    CONSTRAINT ck_rooms_description_not_blank CHECK (description IS NULL OR btrim(description) <> ''),
    CONSTRAINT ck_rooms_bounds_x_non_negative CHECK (bounds_x >= 0),
    CONSTRAINT ck_rooms_bounds_y_non_negative CHECK (bounds_y >= 0),
    CONSTRAINT ck_rooms_bounds_width_positive CHECK (bounds_width > 0),
    CONSTRAINT ck_rooms_bounds_height_positive CHECK (bounds_height > 0)
);

CREATE INDEX ix_rooms_floor ON rooms (floor_id);

CREATE TABLE points_of_interest (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    node_id bigint NOT NULL,
    room_id bigint,
    name varchar(120) NOT NULL,
    category varchar(50) NOT NULL,
    CONSTRAINT pk_points_of_interest PRIMARY KEY (id),
    CONSTRAINT fk_points_of_interest_node_id FOREIGN KEY (node_id) REFERENCES nodes (id),
    CONSTRAINT fk_points_of_interest_room_id FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT uq_poi_node UNIQUE (node_id),
    CONSTRAINT ck_points_of_interest_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_points_of_interest_category_format CHECK (category ~ '^[a-z][a-z0-9-]*$')
);

